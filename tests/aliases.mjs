import assert from 'node:assert/strict';
import {initial,run,expandCisco} from '../lib/labs.ts';
assert.equal(expandCisco('sh vlan br'),'show vlan brief');
assert.equal(expandCisco('do sh run'),'do show running-config');
assert.equal(expandCisco('sh v br'),'show vlan brief');
assert.equal(expandCisco('sh eth sum'),'show etherchannel summary');
assert.equal(expandCisco('sh i'),'sh i','ambiguous abbreviations must remain unsupported');
assert.equal(expandCisco('s v br'),'s v br','one-letter command roots must remain unsupported');
let s=initial('vlan');
for(const cmd of ['en','conf t','vlan 10','name VENDAS','exit','int gi0/1','sw mo acc','sw acc vlan 10','end','sh vlan br'])s=run(s,cmd).state;
assert.equal(s.devices.SW1.vlans[10],'VENDAS');
assert.equal(s.devices.SW1.ports['gi0/1'].vlan,10);
assert.equal(s.mode,'exec');
assert.match(run(initial(),'?').output,/Modo EXEC de usuário/);
assert.match(run(run(initial(),'enable').state,'?').output,/Modo EXEC privilegiado/);
let config=run(run(initial(),'enable').state,'configure terminal').state;
assert.match(run(config,'?').output,/Configuração global/);
config=run(config,'vlan 10').state;
assert.match(run(config,'?').output,/Configuração de VLAN/);
config=run(config,'exit').state;
config=run(config,'interface gi0/1').state;
assert.match(run(config,'?').output,/Configuração de interface switchport/);
assert.match(run(run(initial(),'enable').state,'sh i').output,/^%/);
console.log('Atalhos Cisco: OK');
